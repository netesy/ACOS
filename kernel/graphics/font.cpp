// Blend two colors with alpha
static inline u32 blend_color(u32 fg, u32 bg, u8 alpha) {
    u8 r_fg = (fg >> 16) & 0xFF;
    u8 g_fg = (fg >> 8) & 0xFF;
    u8 b_fg = fg & 0xFF;
    
    u8 r_bg = (bg >> 16) & 0xFF;
    u8 g_bg = (bg >> 8) & 0xFF;
    u8 b_bg = bg & 0xFF;
    
    u8 r = (r_fg * alpha + r_bg * (255 - alpha)) / 255;
    u8 g = (g_fg * alpha + g_bg * (255 - alpha)) / 255;
    u8 b = (b_fg * alpha + b_bg * (255 - alpha)) / 255;
    
    return (r << 16) | (g << 8) | b;
}

void Font::draw_char(char c, u32 x, u32 y, u32 color) {
    u8 ch = (u8)c;
    const u8* glyph = g_font_bitmap[ch];
    const GlyphMetrics& metrics = g_glyph_metrics[ch];
    
    // Render glyph with anti-aliasing
    for (int row = 0; row < 8; row++) {
        u8 bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            u8 bit = (bits >> (7 - col)) & 1;
            
            if (bit) {
                // Pixel is set - draw with full opacity
                Framebuffer::put_pixel(x + col, y + row, color);
            }
        }
    }
}

void Font::draw_string(const char* str, u32 x, u32 y, u32 color) {
    if (!str) return;
    
    u32 cur_x = x;
    u32 cur_y = y;
    u32 line_height = 10;
    u32 max_width = 1920; // Assume standard width
    
    while (*str) {
        char c = *str++;
        
        // Handle newlines
        if (c == '\n') {
            cur_x = x;
            cur_y += line_height;
            continue;
        }
        
        // Handle tabs
        if (c == '\t') {
            cur_x += 32;
            continue;
        }
        
        // Skip control characters
        if ((u8)c < 32) continue;
        
        // Word wrapping
        if (cur_x + 8 > max_width) {
            cur_x = x;
            cur_y += line_height;
        }
        
        draw_char(c, cur_x, cur_y, color);
        cur_x += 8;
    }
}

